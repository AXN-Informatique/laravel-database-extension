# Laravel Database Extension

- Extends Eloquent/Query Builder: `joinRel()`/`leftJoinRel()`/`rightJoinRel()` (joins from relationship definitions), `whereHasIn()`, `whereLike()`, `orderByNatural()`, extended `SoftDeletes` with `withoutTrashedExcept($id)`.
- IMPORTANT: Activate `database-extension-development` skill for supported relationships, usage patterns and examples.
